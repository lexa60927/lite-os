/**
 * Пример шейдер-мода: тёплый закат. Работает без newton-блоков — только код,
 * который вставляется в материал чанков, поэтому применяется и без перезагрузки
 * (кнопка «Применить шейдеры сейчас» в Настройки → Моды).
 *
 * Точка frag — «албедо × свет» до тонмаппинга: здесь правят оттенок, контраст,
 * цвет по тайлу. uDay/uDusk/uNight уже посчитаны игрой, uAmount — ручка из
 * настроек (её видно слайдером, можно крутить на лету: game.mods.setUniform('uAmount', .8)).
 *
 * Никакого свечения и bloom: моды затемняют и подкрашивают, а не раздувают яркость.
 */
export default {
  id: 'warmdusk',
  name: 'Тёплый закат',
  version: '1.0',
  author: 'пример',
  description: 'Последние минуты дня становятся золотистыми; яркость не растёт',
  enabledByDefault: false,

  shader: {
    name: 'Тёплый закат',
    uniforms: { uAmount: 0.55 },
    frag: `
      float k = clamp(uDusk * uAmount, 0.0, 1.0);
      col = mix(col, col * vec3(1.16, 1.0, 0.84) + vec3(0.022, 0.004, 0.0), k);
      // нижняя половина кадра холоднее: закат сверху, тень земли снизу
      col = mix(col, col * vec3(0.94, 0.98, 1.06), k * clamp(1.0 - vWorld.y / 48.0, 0.0, 1.0) * 0.5);
    `,
  },
};
