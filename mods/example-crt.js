/**
 * Пример мода «экранного» вида: ЭЛТ-монитор. Показывает обе оставшиеся точки —
 * fragFinal (воксельный материал, уже после дымки) и post (грейд-проход, нужен
 * включённый уровень «Ультра»: без постобработки game/postfx.js не работает).
 *
 * Эффект сделан затемнением и лёгким обесцвечиванием. Никакого свечения: оно
 * здесь выглядело бы как мусор между строками развёртки.
 */
export default {
  id: 'crt',
  name: 'ЭЛТ-монитор',
  version: '1.0',
  author: 'пример',
  description: 'Скан-линии, лёгкое обесцвечивание и зерно. Шейдер + пост-проход',
  enabledByDefault: false,

  shader: {
    name: 'ЭЛТ-монитор',
    uniforms: { uScan: 0.4 },
    fragFinal: `
      // зерно по координатам тайлы: без него flat-поверхности выглядят пластмассовыми
      float n = fract(sin(dot(vUv * vec2(431.7, 927.3), vec2(12.9898, 78.233))) * 43758.5453);
      col += (n - 0.5) * 0.02 * uScan;
    `,
    post: `
      float lines = 0.5 + 0.5 * sin(vUv.y * 780.0);
      c.rgb *= 1.0 - uScan * 0.2 * lines;
      float lum = dot(c.rgb, vec3(0.299, 0.587, 0.114));
      c.rgb = mix(c.rgb, vec3(lum), uScan * 0.16);
      // по краям кадра чуть холоднее и темнее — линза, а не виньетка из меню
      float r = length(vUv - 0.5);
      c.rgb *= 1.0 - uScan * 0.1 * smoothstep(0.25, 0.72, r);
    `,
  },
};
